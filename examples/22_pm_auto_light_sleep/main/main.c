/*
 * Пример 22. Автоматический лёгкий сон.
 *
 * В примере 18 программа сама вызывала esp_light_sleep_start().
 * Здесь она этого не делает. Вместо этого включено управление
 * питанием (power management):
 *
 *   пока все задачи спят в vTaskDelay или на очереди,
 *   FreeRTOS останавливает свой тик (tickless idle),
 *   а драйвер питания уводит чип в лёгкий сон;
 *   к моменту, когда задержка кончится, чип просыпается сам,
 *   и ESP_LOGI выполняется как обычно.
 *
 * Снаружи это выглядит как программа, которая «просто ждёт 3 секунды».
 * Ток между строками лога при этом падает так же, как в ручном лёгком сне.
 * Измерять его удобно в разрыве питания 3.3 В, не в разрыве USB:
 * USB-порт компьютера кормит ещё и преобразователь на плате.
 *
 * Частоты 40 и 160 МГц — обычная вилка ESP32-C3.
 * 160 МГц процессор берёт, когда есть работа.
 * 40 МГц — нижняя ступень, с неё же он уходит в лёгкий сон.
 * Понижение частоты без сна называется DFS (dynamic frequency scaling).
 * В этом примере включены обе возможности: и DFS, и light_sleep_enable.
 *
 * Wi-Fi сюда специально не добавлен. С сетью автоматический сон тоже
 * работает, но только вместе с модемным сном из примера 12 и с более
 * длинными паузами: радио обязано просыпаться на маяки роутера.
 */

#include "freertos/FreeRTOS.h"
#include "freertos/task.h"
#include "esp_log.h"
#include "esp_pm.h"

static const char *TAG = "pm";

void app_main(void)
{
    esp_pm_config_t power = {
        .max_freq_mhz = 160,
        .min_freq_mhz = 40,
        .light_sleep_enable = true,
    };
    ESP_ERROR_CHECK(esp_pm_configure(&power));
    ESP_LOGI(TAG, "автоматический лёгкий сон включён");
    ESP_LOGI(TAG, "между строками чип спит, хотя esp_light_sleep_start() в коде нет");

    int awake = 0;
    while (true) {
        awake++;
        ESP_LOGI(TAG, "бодрствование %d", awake);
        /*
         * 3 секунды — достаточная пауза, чтобы сон вообще наступил.
         * Слишком короткие delay планировщик не заменяет сном:
         * вход и выход стоили бы дольше самой паузы.
         */
        vTaskDelay(pdMS_TO_TICKS(3000));
    }
}
