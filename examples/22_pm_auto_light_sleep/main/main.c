/*
 * Пример 22. Автоматический лёгкий сон.
 *
 * В примере 18 программа сама вызывала esp_light_sleep_start().
 * Здесь она этого не делает. Вместо этого включено управление
 * питанием (power management):
 *
 *   пока все задачи спят в vTaskDelay или на очереди,
 *   FreeRTOS останавливает свой тик (tickless idle),
 *   а драйвер питания уводит чип в лёгкий сон;
 *   к моменту, когда задержка кончится, чип просыпается сам,
 *   и ESP_LOGI выполняется как обычно.
 *
 * Снаружи это выглядит как программа, которая «просто ждёт 3 секунды».
 * Ток между строками лога при этом падает так же, как в ручном лёгком сне.
 * Измерять его удобно в разрыве питания 3.3 В, не в разрыве USB:
 * USB-порт компьютера кормит ещё и преобразователь на плате.
 *
 * Частоты 40 и 160 МГц — обычная вилка ESP32-C3.
 * 160 МГц процессор берёт, когда есть работа.
 * 40 МГц — нижняя ступень, с неё же он уходит в лёгкий сон.
 * Понижение частоты без сна называется DFS (dynamic frequency scaling).
 * В этом примере включены обе возможности: и DFS, и light_sleep_enable.
 *
 * Wi-Fi сюда специально не добавлен. С сетью автоматический сон тоже
 * работает, но только вместе с модемным сном из примера 12 и с более
 * длинными паузами: радио обязано просыпаться на маяки роутера.
 */

/*
 * Библиотеки:
 * freertos/FreeRTOS.h и task.h — vTaskDelay на 3 секунды. Пока все задачи спят,
 *   планировщик сам останавливает тик, и драйвер питания уводит чип в сон.
 * esp_log.h — строки между паузами. По ним видно, что программа «просто ждёт».
 * esp_pm.h — esp_pm_configure включает автоматический лёгкий сон и вилку частот.
 *   esp_light_sleep_start в этом файле нет и не нужен.
 */
#include "freertos/FreeRTOS.h" /* Типы планировщика. */
#include "freertos/task.h"     /* vTaskDelay. Пока задача в нём спит, чип может уйти в сон. */
#include "esp_log.h"           /* Строки между паузами показывают, что программа проснулась. */
#include "esp_pm.h"            /* esp_pm_configure включает автоматический лёгкий сон и смену частоты. */

static const char *TAG = "pm"; /* Подпись строк монитора. */

void app_main(void) /* Точка входа. */
{
    esp_pm_config_t power = { /* Политика питания: частоты и разрешение сна. */
        .max_freq_mhz = 160, /* Потолок, когда есть работа. Для C3 это штатные 160 МГц. */
        .min_freq_mhz = 40,  /* Нижняя ступень. С неё же чип уходит в лёгкий сон. */
        .light_sleep_enable = true, /* Разрешить сон, когда задачи только ждут. */
    };
    /* Применить политику. Дальше сон случается сам, отдельного вызова сна нет. */
    ESP_ERROR_CHECK(esp_pm_configure(&power)); /* Включить политику. Отдельного вызова сна в программе нет. */
    ESP_LOGI(TAG, "автоматический лёгкий сон включён"); /* Подтверждение, что настройка прошла. */
    ESP_LOGI(TAG, "между строками чип спит, хотя esp_light_sleep_start() в коде нет"); /* Чем этот пример отличается от 18. */

    int awake = 0; /* Сколько раз задача просыпалась. Число растёт, потому что память во сне жива. */
    while (true) { /* Бесконечный цикл «проснуться, напечатать, заснуть». */
        awake++; /* Плюс один к счётчику пробуждений. */
        ESP_LOGI(TAG, "бодрствование %d", awake); /* Эта строка видна, когда чип не спит. */
        /*
         * 3 секунды — достаточная пауза, чтобы сон вообще наступил.
         * Слишком короткие delay планировщик не заменяет сном:
         * вход и выход стоили бы дольше самой паузы.
         */
        vTaskDelay(pdMS_TO_TICKS(3000)); /* Три секунды сна. Короче пауза — и вход в сон может не окупиться. */
    }
}
